<?php

namespace Database\Seeders;

use Illuminate\Support\Facades\DB;

/**
 * مواد وأساتذة القسم التجاري (الفصل الأول، سنة أولى وسنة ثانية).
 * يعيد استعمال منطق ProgramCoursesSeeder (إنشاء/تحديث بدون تكرار، وحسابات المعلمين بنمط <الاسم>-trainer@edu-bridge.com).
 */
class CommerceCoursesSeeder extends ProgramCoursesSeeder
{
    private const DEPARTMENT = 'تجاري';

    /** اسم الدورة كما هو بقاعدة البيانات => مفتاح الخطة */
    private const PROGRAMS = [
        'banking'    => 'مصارف و تأمين',
        'accounting' => 'محاسبة',
        'business'   => 'إدارة اعمال',
        'hr'         => 'موارد بشرية',
        'ebusiness'  => 'إدارة اعمال الكترونية',
    ];

    public function run(): void
    {
        $departmentId = DB::table('departments')->where('name', self::DEPARTMENT)->value('department_id');
        if (!$departmentId) {
            $this->command->warn('⚠️ القسم التجاري غير موجود — تم التخطي');

            return;
        }

        // الدورتان الناقصتان تُنشآن مرة واحدة تحت القسم التجاري
        foreach (self::PROGRAMS as $name) {
            if (!DB::table('programs')->where('name', $name)->exists()) {
                DB::table('programs')->insert([
                    'name' => $name, 'department_id' => $departmentId,
                    'created_at' => now(), 'updated_at' => now(),
                ]);
                $this->command->info("➕ أُنشئت الدورة: $name");
            }
        }

        $this->apply($this->commercePlans());
    }

    /** مطابقة تامة للاسم (حتى لا تلتقط «إدارة اعمال» دورة «إدارة اعمال الكترونية»). */
    protected function resolveProgram(array $needles): ?int
    {
        return DB::table('programs')->where('name', $needles[0])->value('id');
    }

    private function commercePlans(): array
    {
        // سنة أولى فصل أول: نفس المواد لكل الدورات
        $firstYear = [
            ['محاسبة 1', ['ديمة اللحام']],
            ['اللغة الإنكليزية', ['بلال']],
            ['مبادئ تسويق', ['نهيل']],
            ['اللغة العربية', ['نرجس']],
            ['تحليل جزئي', ['دارين']],
            ['مبادئ إدارة', ['سمير']],
            ['إحصاء', ['ريم']],
            ['أخلاقيات مهنية', []],
            ['مدخل اقتصاد', ['أسعد']],
        ];

        $plans = [];
        foreach (self::PROGRAMS as $key => $name) {
            $plans[$key] = ['program_like' => [$name], 'plan' => [1 => [1 => $firstYear]]];
        }

        // سنة ثانية فصل أول
        $plans['banking']['plan'][2][1] = [
            ['إدارة مالية', ['محمد درويش']],
            ['محاسبة منشآت', []],
            ['عمليات مصرفية', ['دارين']],
            ['تجارة خارجية', []], // الأستاذ عدنان مسافر: المادة بلا معلم حالياً
            ['إنكليزي تقني', ['شريف علي']],
            ['تأمين', ['عثمان']],
            ['رياضيات تأمين', ['ريم']],
            ['تمويل قصير', ['لينا']],
        ];
        $plans['accounting']['plan'][2][1] = [
            ['إدارة مالية', ['محمد درويش']],
            ['محاسبة منشآت', []],
            ['محاسبة متوسطة', ['عثمان']],
            ['محاسبة ضريبية', ['عثمان']],
            ['إنكليزي تقني', ['شريف علي']],
            ['محاسبة مالية', ['عثمان']],
            ['محاسبة تكاليف', ['عثمان']],
            ['محاسبة شركات', ['عثمان']],
        ];
        $plans['ebusiness']['plan'][2][1] = [
            ['إدارة مالية', ['محمد درويش']],
            ['تسويق خدمي', []],
            ['تكنولوجيا أمن معلومات', []],
            ['إنكليزي تقني', ['شريف علي']],
            ['تسويق رقمي', []],
            ['تجارة إلكترونية', []],
        ];
        $plans['business']['plan'][2][1] = [
            ['إدارة مالية', ['محمد درويش']],
            ['سلوك مستهلك', []],
            ['قيادة إدارية', []],
            ['تسويق خدمي', []],
            ['إنكليزي تقني', ['شريف علي']],
            ['أساليب كمية', []],
            ['إدارة دولية', []],
            ['موارد بشرية متقدمة 1', []],
        ];
        $plans['hr']['plan'][2][1] = [
            ['إدارة مالية', ['محمد درويش']],
            ['مسار مهني', []],
            ['السلوك التنظيمي', []],
            ['قيادة إدارية', []],
            ['اتجاهات موارد', []],
            ['إنكليزي تقني', ['شريف علي']],
            ['تنظيم إداري', []],
            ['إدارة تنوع', []],
            ['إدارة توظيف', []],
            ['إدارة استراتيجية', []],
        ];

        return $plans;
    }
}
